/**
 * Regenerate a state's election-history aggregate (party seat tallies per year)
 * directly from its authoritative seed, so the totals always match the map.
 * Preserves the existing interface / const / getter names.
 *
 *   node scripts/build-election-history.mjs <CODE> <base> [--write]
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [CODE, BASE] = process.argv.slice(2);
const WRITE = process.argv.includes('--write');
if (!CODE || !BASE) { console.error('usage: <CODE> <base> [--write]'); process.exit(1); }
const seedTxt = readFileSync(`C:/K/data/seed/${BASE}-constituencies.ts`, 'utf8');
const histFile = `C:/K/data/seed/${BASE}-election-history.ts`;
const histTxt = readFileSync(histFile, 'utf8');

const years = [...new Set([...seedTxt.matchAll(/winner(\d{4}):/g)].map((m) => +m[1]))].sort((a, b) => b - a);
const blocks = [...seedTxt.matchAll(/\{ acNo: \d+,[^}]*\}/g)].map((m) => m[0]);
const tallies = {};
for (const y of years) {
  const t = {};
  for (const b of blocks) { const w = (b.match(new RegExp(`winner${y}: '([^']*)'`)) || [])[1]; if (w) t[w] = (t[w] || 0) + 1; }
  tallies[y] = t;
}
const IFACE = (histTxt.match(/export interface (\w+)/) || [])[1];
const CONST = (histTxt.match(/export const (\w+):/) || [])[1];
const fns = [...histTxt.matchAll(/export function (\w+)/g)].map((m) => m[1]);
console.log(`${CODE}: years ${years.join(', ')} | iface ${IFACE} | const ${CONST} | fns ${fns.join(', ')}`);
for (const y of years) console.log(`  ${y}:`, JSON.stringify(tallies[y]), 'total', Object.values(tallies[y]).reduce((a, b) => a + b, 0));

if (WRITE) {
  const entries = years.map((y) => {
    const t = tallies[y];
    const ruling = Object.entries(t).filter(([k]) => k !== 'IND' && k !== 'OTH' && k !== 'NOTA').sort((a, b) => b[1] - a[1])[0]?.[0] || Object.entries(t).sort((a, b) => b[1] - a[1])[0][0];
    const total = Object.values(t).reduce((a, b) => a + b, 0);
    const pr = Object.entries(t).sort((a, b) => b[1] - a[1]).map(([k, v]) => `      '${k}': ${v},`).join('\n');
    return `  {\n    year: ${y},\n    partyResults: {\n${pr}\n    },\n    totalSeats: ${total},\n    rulingParty: '${ruling}',\n  },`;
  }).join('\n');
  const getByYear = fns.find((f) => /ByYear$/.test(f));
  const getTrend = fns.find((f) => /Trend$/.test(f));
  const out = `/**
 * ${CODE} — Election History Summary (party seat tallies per Assembly election).
 * Auto-generated by scripts/build-election-history.mjs from the authoritative seed
 * (TCPD/ECI). Totals match the constituency map exactly.
 */

export interface ${IFACE} {
  year: number;
  partyResults: Record<string, number>;
  totalSeats: number;
  rulingParty: string;
}

export const ${CONST}: ${IFACE}[] = [
${entries}
];

export function ${getByYear}(year: number) {
  return ${CONST}.find((e) => e.year === year);
}

export function ${getTrend}(party: string) {
  return ${CONST}.map((e) => ({ year: e.year, seats: e.partyResults[party] || 0 }));
}
`;
  writeFileSync(histFile, out, 'utf8');
  console.log('WROTE', histFile);
}
