/** Resolve localized term with safe fallback to English */
export function getLocalizedTerm(
  dict: Record<string, TermLocalization>,
  key: string,
  lang: string
): string {
  const entry = dict[key];
  if (!entry) return key;
  const l = lang as SupportedLanguage;
  return entry[l] || entry['en'] || key;
}
