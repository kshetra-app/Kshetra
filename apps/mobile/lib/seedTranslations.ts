/**
 * Localizes a single Post object for the target language.
 * Preserves user-generated posts as-is while translating seed posts seamlessly.
 */
export function getLocalizedPost(post: Post, language: string): Post {
  if (!language || language === 'en') return post;

  const postTrans = SEED_POST_TRANSLATIONS[post.id]?.[language];
  const authorTrans = AUTHOR_NAME_LOCALES[post.author.displayName]?.[language];
  const constituencyTrans = post.constituencyName
    ? CONSTITUENCY_NAME_LOCALES[post.constituencyName]?.[language]
    : undefined;

  let localizedPoll = post.poll;
  if (post.poll && postTrans?.pollQuestion) {
    localizedPoll = {
      ...post.poll,
      question: postTrans.pollQuestion,
      options: post.poll.options.map((opt) => ({
        ...opt,
        label: postTrans.pollOptions?.[opt.id] ?? opt.label,
      })),
    };
  }

  return {
    ...post,
    content: postTrans?.content ?? post.content,
    author: {
      ...post.author,
      displayName: authorTrans ?? post.author.displayName,
    },
    constituencyName: constituencyTrans ?? post.constituencyName,
    hashtags: postTrans?.hashtags ?? post.hashtags,
    poll: localizedPoll,
  };
}

/**
 * Localizes an array of Posts for the target language.
 */
export function getLocalizedPosts(posts: Post[], language: string): Post[] {
  if (!language || language === 'en') return posts;
  return posts.map((p) => getLocalizedPost(p, language));
}

