/**
 * Returns localized name for contact
 */
export function getLocalizedContactName(name: string, lang: string): string {
  if (!name || lang === 'en') return name;
  return CONTACT_NAMES[name]?.[lang] || name;
}

/**
 * Returns localized role for contact
 */
export function getLocalizedContactRole(role: string, lang: string): string {
  if (!role || lang === 'en') return role;
  return ROLES[role]?.[lang] || role;
}

/**
 * Returns localized preview / message string
 */
export function getLocalizedDMPreview(text: string, lang: string): string {
  if (!text || lang === 'en') return text;
  return MESSAGE_PREVIEWS[text]?.[lang] || text;
}
