/**
 * apps/api/src/__tests__/delimitation-citizen-impact-data-truth.test.ts
 *
 * Dedicated Test Battery for CTO Directive 122 & 123:
 * Residual Electoral Data-Truth Remediation & Provisional Lookup Integrity
 *
 * Enforces the 10 Mandatory Domain Assertions (CTO Directive 123 Section 6):
 * 1. Missing canonical incumbent data does not produce a placeholder name ('Sitting Legislator').
 * 2. Missing canonical party data does not produce a fabricated party ('INC').
 * 3. Missing reservation data is not silently converted to an asserted factual reservation ('GEN').
 * 4. Proposed AC identifiers are never generated by arithmetic (e.g. Math.round(acNo * 1.15)).
 * 5. A regional prefix with no verified candidates does not return all constituencies in the state.
 * 6. Curated entries with multi-AC intersections are not treated as 1:1 single-AC linkages.
 * 7. Ambiguous or incomplete evidence produces regional-only or unavailable (404) output.
 * 8. Properly sourced provisional scenarios remain explicitly non-statutory and distinct from current data.
 * 9. The API DTO, route serialization, and consumers preserve omitted fields without fabricating replacements.
 * 10. All pre-existing Directive 122 protections remain intact: no modulo selection, no silent TS fallback, no synthetic ACs.
 */

import { buildApp } from '../server';
import type { FastifyInstance } from 'fastify';
import {
  delimitationService,
  POSTAL_DIRECTORY_CLASSIFICATION,
  CURATED_PROVISIONAL_PIN_DIRECTORY,
  PIN_PREFIX_MAPPING,
} from '../services/delimitationService';
import * as stateDataModule from '../services/stateData';

describe('CTO Directive 123 — Residual Electoral Data-Truth & Provisional Lookup Integrity', () => {
  let app: FastifyInstance;

  beforeAll(async () => {
    app = await buildApp();
  });

  afterAll(async () => {
    await app.close();
  });

  describe('Assertion 1: Missing canonical incumbent data does not produce a placeholder name', () => {
    it('preserves absence of sittingMLA when canonical constituency has no incumbent name', () => {
      // Spy on getConstituency to return a brief with currentMLA absent/empty
      const spy = jest.spyOn(stateDataModule, 'getConstituency').mockReturnValueOnce({
        id: 'TS-AC-63',
        name: 'Nampally',
        acNo: 63,
        stateCode: 'TS',
        district: 'Hyderabad',
        reservationStatus: 'GEN',
        currentParty: 'AIMIM',
        currentMLA: '', // Missing / empty
      });

      const res = delimitationService.getCitizenImpact('500004'); // Nampally
      expect(res.status).toBe('LINKED_PROVISIONAL');
      expect(res.currentConstituency).toBeDefined();
      expect(res.currentConstituency?.acNo).toBe(63);
      // Strictly undefined — NEVER 'Sitting Legislator' or any placeholder string!
      expect(res.currentConstituency?.sittingMLA).toBeUndefined();
      expect(res.currentConstituency?.party).toBe('AIMIM');

      spy.mockRestore();
    });
  });

  describe('Assertion 2: Missing canonical party data does not produce a fabricated party', () => {
    it('preserves absence of party when canonical constituency has no incumbent party', () => {
      const spy = jest.spyOn(stateDataModule, 'getConstituency').mockReturnValueOnce({
        id: 'TS-AC-63',
        name: 'Nampally',
        acNo: 63,
        stateCode: 'TS',
        district: 'Hyderabad',
        reservationStatus: 'GEN',
        currentParty: '', // Missing / empty
        currentMLA: 'Test Legislator',
      });

      const res = delimitationService.getCitizenImpact('500004');
      expect(res.status).toBe('LINKED_PROVISIONAL');
      expect(res.currentConstituency).toBeDefined();
      expect(res.currentConstituency?.sittingMLA).toBe('Test Legislator');
      // Strictly undefined — NEVER 'INC' or any synthetic default!
      expect(res.currentConstituency?.party).toBeUndefined();

      spy.mockRestore();
    });
  });

  describe('Assertion 3: Missing reservation data is not silently converted to an asserted factual reservation', () => {
    it('preserves absence of reservation when canonical constituency lacks reservation status', () => {
      const spy = jest.spyOn(stateDataModule, 'getConstituency').mockReturnValueOnce({
        id: 'TS-AC-63',
        name: 'Nampally',
        acNo: 63,
        stateCode: 'TS',
        district: 'Hyderabad',
        reservationStatus: '' as any, // Missing / unclassified
        currentParty: 'AIMIM',
        currentMLA: 'Jaffar Hussain',
      });

      const res = delimitationService.getCitizenImpact('500004');
      expect(res.status).toBe('LINKED_PROVISIONAL');
      expect(res.currentConstituency).toBeDefined();
      // Strictly undefined — NEVER silently defaulted to 'GEN'!
      expect(res.currentConstituency?.reservation).toBeUndefined();

      spy.mockRestore();
    });
  });

  describe('Assertion 4: Proposed AC identifiers are never generated by arithmetic from existing AC numbers', () => {
    it('verifies proposedConstituency is absent in default lookup without ungrounded proposals', () => {
      // In all curated PINs, default lookup without scenario model must omit proposedConstituency
      for (const pin of ['500002', '500004', '500010', '520001']) {
        const res = delimitationService.getCitizenImpact(pin);
        expect(res.status).toBe('LINKED_PROVISIONAL');
        expect(res.proposedConstituency).toBeUndefined();
        expect(res.impactAnalysis).toBeUndefined();
      }
    });

    it('proves scenario identifiers are scenario-scoped and never generated via Math.round(acNo * 1.15)', () => {
      const res = delimitationService.getCitizenImpact('500004', { scenarioId: 'census_2026_expansion' });
      expect(res.proposedConstituency).toBeDefined();
      // Arithmetic check: 63 * 1.15 = 72.45 -> Math.round = 72
      // Must NOT be numerical 72!
      expect(res.proposedConstituency?.acNo).toBeUndefined();
      expect(res.proposedConstituency?.scenarioAcIdentifier).toBe('SCENARIO-TS-63P');
      expect(res.proposedConstituency?.statutoryStatus).toBe('NON_STATUTORY_HYPOTHETICAL_SCENARIO');
    });
  });

  describe('Assertion 5: A regional prefix with no verified candidates does not return all constituencies in the state', () => {
    it('proves Maharashtra PIN 400001 does NOT return all 288 constituencies of the state', () => {
      const res = delimitationService.getCitizenImpact('400001');
      expect(res.status).toBe('REGIONAL_ONLY');
      expect(res.location.stateCode).toBe('MH');
      // Substring matching & statewide dump eliminated: candidateConstituencies must be undefined
      expect(res.candidateConstituencies).toBeUndefined();
      expect(res.currentConstituency).toBeUndefined();
      expect(res.linkageNotice).toContain('Candidate constituencies cannot be reliably derived');
    });

    it('proves Delhi PIN 110001 does NOT return all 70 constituencies of Delhi as candidates', () => {
      const res = delimitationService.getCitizenImpact('110001');
      expect(res.status).toBe('REGIONAL_ONLY');
      expect(res.location.stateCode).toBe('DL');
      expect(res.candidateConstituencies).toBeUndefined();
      expect(res.currentConstituency).toBeUndefined();
    });

    it('proves Karnataka PIN 560001 does NOT return all 224 constituencies of Karnataka', () => {
      const res = delimitationService.getCitizenImpact('560001');
      expect(res.status).toBe('REGIONAL_ONLY');
      expect(res.location.stateCode).toBe('KA');
      expect(res.candidateConstituencies).toBeUndefined();
      expect(res.currentConstituency).toBeUndefined();
    });
  });

  describe('Assertion 6: Curated entries with multi-AC intersections are not treated as 1:1 single-AC linkages', () => {
    it('proves Hyderabad GPO PIN 500001 returns documented AMBIGUOUS_CANDIDATES without assigning a single AC', () => {
      const res = delimitationService.getCitizenImpact('500001');
      expect(res.status).toBe('AMBIGUOUS_CANDIDATES');
      expect(res.currentConstituency).toBeUndefined();
      expect(res.proposedConstituency).toBeUndefined();
      expect(res.impactAnalysis).toBeUndefined();
      expect(Array.isArray(res.candidateConstituencies)).toBe(true);
      expect(res.candidateConstituencies?.length).toBe(3); // Goshamahal (65), Nampally (63), Malakpet (58)

      const acNos = res.candidateConstituencies?.map((c) => c.acNo);
      expect(acNos).toContain(65);
      expect(acNos).toContain(63);
      expect(acNos).toContain(58);

      expect(res.linkageNotice).toContain('intersects 3 assembly constituencies');
      expect(res.linkageNotice).toContain('Goshamahal');
      expect(res.linkageNotice).toContain('Nampally');
      expect(res.linkageNotice).toContain('Malakpet');
    });

    it('proves Mehdipatnam PIN 500028 returns documented candidates for Karwan and Nampally', () => {
      const res = delimitationService.getCitizenImpact('500028');
      expect(res.status).toBe('AMBIGUOUS_CANDIDATES');
      expect(res.currentConstituency).toBeUndefined();
      const acNos = res.candidateConstituencies?.map((c) => c.acNo);
      expect(acNos).toEqual([64, 63]); // Karwan (64) and Nampally (63)
    });

    it('proves Banjara Hills PIN 500034 returns documented candidates for Khairatabad and Jubilee Hills', () => {
      const res = delimitationService.getCitizenImpact('500034');
      expect(res.status).toBe('AMBIGUOUS_CANDIDATES');
      expect(res.currentConstituency).toBeUndefined();
      const acNos = res.candidateConstituencies?.map((c) => c.acNo);
      expect(acNos).toEqual([60, 61]); // Khairatabad (60) and Jubilee Hills (61)
    });
  });

  describe('Assertion 7: Ambiguous or incomplete evidence produces regional-only or unavailable output', () => {
    it('unmapped postal prefix fails closed with 404 PIN_NOT_FOUND', async () => {
      const res = await app.inject({
        method: 'GET',
        url: '/api/v1/delimitation/impact/999999',
      });
      expect(res.statusCode).toBe(404);
      const json = JSON.parse(res.payload);
      expect(json.code).toBe('PIN_NOT_FOUND');
    });

    it('non-6-digit PIN fails closed with 400 FST_ERR_VALIDATION', async () => {
      const res = await app.inject({
        method: 'GET',
        url: '/api/v1/delimitation/impact/12345',
      });
      expect(res.statusCode).toBe(400);
      const json = JSON.parse(res.payload);
      expect(json.code).toBe('FST_ERR_VALIDATION');
    });
  });

  describe('Assertion 8: Properly sourced provisional scenarios remain explicitly non-statutory and distinct from current data', () => {
    it('verifies that scenario simulations explicitly disclose non-statutory status and spatial caveats', () => {
      const res = delimitationService.getCitizenImpact('500004', { scenarioId: 'expansion_2026' });
      expect(res.status).toBe('LINKED_PROVISIONAL');
      expect(res.currentConstituency).toBeDefined();
      expect(res.currentConstituency?.name).toBe('Nampally');

      expect(res.proposedConstituency).toBeDefined();
      expect(res.proposedConstituency?.statutoryStatus).toBe('NON_STATUTORY_HYPOTHETICAL_SCENARIO');
      expect(res.impactAnalysis).toBeDefined();
      expect(res.impactAnalysis?.isScenarioEstimate).toBe(true);
      expect(res.impactAnalysis?.spatialCaveat).toBeDefined();
      expect(res.impactAnalysis?.explanation).toContain('constitutionally frozen');
    });

    it('supports scenario projection lookup via proposalId parameter', () => {
      const res = delimitationService.getCitizenImpact('500004', { proposalId: 'prop-ts-2026-v1' });
      expect(res.status).toBe('LINKED_PROVISIONAL');
      expect(res.proposedConstituency?.scenarioAcIdentifier).toBe('SCENARIO-TS-63P');
      expect(res.impactAnalysis?.explanation).toContain("prop-ts-2026-v1");
    });

    it('throws 500 CONSTITUENCY_LOOKUP_ERROR if canonical constituency cannot be found in stateData', () => {
      const spy = jest.spyOn(stateDataModule, 'getConstituency').mockReturnValueOnce(null);
      expect(() => delimitationService.getCitizenImpact('500004')).toThrow('Canonical constituency TS-AC-63 not found');
      spy.mockRestore();
    });
  });

  describe('Assertion 9: The API DTO, route serialization, and consumers preserve omitted fields without fabricating replacements', () => {
    it('route GET /api/v1/delimitation/impact/:pinCode serializes clean envelope without synthetic fallback strings', async () => {
      const res = await app.inject({
        method: 'GET',
        url: '/api/v1/delimitation/impact/500004',
      });
      expect(res.statusCode).toBe(200);
      const json = JSON.parse(res.payload);
      expect(json.success).toBe(true);
      expect(json.data.status).toBe('LINKED_PROVISIONAL');
      expect(json.data.currentConstituency).toBeDefined();

      // Ensure that undefined fields are absent from JSON payload
      expect(json.data.proposedConstituency).toBeUndefined();
      expect(json.data.impactAnalysis).toBeUndefined();
      expect(json.data.candidateConstituencies).toBeUndefined();

      // Raw payload string inspection: prove 'Sitting Legislator' and arithmetic do not appear anywhere in payload
      expect(res.payload).not.toContain('Sitting Legislator');
      expect(res.payload).not.toContain('Math.round');
      expect(res.payload).not.toContain('(Projected)');
    });
  });

  describe('Assertion 10: All pre-existing Directive 122 protections remain intact', () => {
    it('modulo arithmetic is strictly absent: suffix variations do not change outcome', () => {
      const r1 = delimitationService.getCitizenImpact('110001');
      const r2 = delimitationService.getCitizenImpact('110099');
      expect(r1.status).toBe('REGIONAL_ONLY');
      expect(r2.status).toBe('REGIONAL_ONLY');
      expect(r1.currentConstituency).toBeUndefined();
      expect(r2.currentConstituency).toBeUndefined();
    });

    it('directory classification is strictly exposed as APPROXIMATE_REGIONAL_CLASSIFICATION', () => {
      expect(POSTAL_DIRECTORY_CLASSIFICATION).toBe('APPROXIMATE_REGIONAL_CLASSIFICATION');
    });

    it('boundary simulation continues to function deterministically with Hare-Niemeyer', () => {
      const sim = delimitationService.simulateBoundaries('TS', { mode: 'equal_population', seats: '130' });
      expect(sim.stateCode).toBe('TS');
      expect(sim.targetSeats).toBe(130);
      expect(sim.districtBreakdown.length).toBeGreaterThan(0);
      expect(sim.scenarioEnclosure.isScenario).toBe(true);
    });
  });
});
